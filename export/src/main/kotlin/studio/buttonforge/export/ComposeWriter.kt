package studio.buttonforge.export

import studio.buttonforge.document.Document
import studio.buttonforge.document.appearance.BlendMode
import studio.buttonforge.document.appearance.StrokeCap
import studio.buttonforge.document.appearance.StrokeJoin

/** A Kotlin file that builds a Jetpack Compose ImageVector, for projects that do not use XML drawables. */
internal object ComposeWriter {
    private const val TARGET = "Compose"

    fun write(doc: Document, items: List<DrawItem>, report: ReportBuilder, identifier: String): String {
        val sb = StringBuilder()
        sb.append(
            """
            // Generated by Button Forge Studio. Add a package line at the top to match your project.
            import androidx.compose.ui.geometry.Offset
            import androidx.compose.ui.graphics.Brush
            import androidx.compose.ui.graphics.Color
            import androidx.compose.ui.graphics.PathFillType
            import androidx.compose.ui.graphics.SolidColor
            import androidx.compose.ui.graphics.StrokeCap
            import androidx.compose.ui.graphics.StrokeJoin
            import androidx.compose.ui.graphics.vector.ImageVector
            import androidx.compose.ui.graphics.vector.path
            import androidx.compose.ui.unit.dp

            """.trimIndent(),
        )
        sb.append("\n")
        sb.append("val $identifier: ImageVector = ImageVector.Builder(\n")
        sb.append("    name = \"$identifier\",\n")
        sb.append("    defaultWidth = ${Format.num(doc.canvas.width)}.dp,\n")
        sb.append("    defaultHeight = ${Format.num(doc.canvas.height)}.dp,\n")
        sb.append("    viewportWidth = ${Format.floatLiteral(doc.canvas.width)},\n")
        sb.append("    viewportHeight = ${Format.floatLiteral(doc.canvas.height)},\n")
        sb.append(").apply {\n")

        for (item in items) {
            if (item.hasEffects) report.add(ReportItem(TARGET, item.layer, "الظلال والتوهج والتمويه", Fidelity.Dropped, "ImageVector لا يدعمها"))
            if (item.blend != BlendMode.Normal) report.add(ReportItem(TARGET, item.layer, "نمط المزج", Fidelity.Dropped, "ImageVector لا يدعمه"))
            val s = item.stroke
            if (s != null && s.dash.isNotEmpty() && s.dash.sum() > 0.0) {
                report.add(ReportItem(TARGET, item.layer, "الحد المنقط", Fidelity.Dropped, "يصير الحد متصلًا"))
            }
            sb.append("    path(\n")
            if (s == null) {
                sb.append("        fill = ${brush(item.paint)},\n")
                if (item.alpha < 1.0) sb.append("        fillAlpha = ${Format.floatLiteral(item.alpha)},\n")
                if (item.evenOdd) sb.append("        pathFillType = PathFillType.EvenOdd,\n")
            } else {
                sb.append("        stroke = ${brush(item.paint)},\n")
                if (item.alpha < 1.0) sb.append("        strokeAlpha = ${Format.floatLiteral(item.alpha)},\n")
                sb.append("        strokeLineWidth = ${Format.floatLiteral(s.width)},\n")
                if (s.cap != StrokeCap.Butt) sb.append("        strokeLineCap = StrokeCap.${s.cap.name},\n")
                if (s.join != StrokeJoin.Miter) sb.append("        strokeLineJoin = StrokeJoin.${s.join.name},\n")
                if (s.miter != 4.0) sb.append("        strokeLineMiter = ${Format.floatLiteral(s.miter)},\n")
            }
            sb.append("    ) {\n")
            for (c in item.commands) {
                when (c) {
                    is PathCmd.MoveTo -> sb.append("        moveTo(${f(c.x)}, ${f(c.y)})\n")
                    is PathCmd.CurveTo ->
                        sb.append("        curveTo(${f(c.x1)}, ${f(c.y1)}, ${f(c.x2)}, ${f(c.y2)}, ${f(c.x)}, ${f(c.y)})\n")
                    PathCmd.Close -> sb.append("        close()\n")
                }
            }
            sb.append("    }\n")
        }
        sb.append("}.build()\n")
        return sb.toString()
    }

    private fun f(d: Double) = Format.floatLiteral(d)

    private fun color(argb: Int) = "Color(0x${"%08X".format(argb)})"

    private fun stops(list: List<FlatStop>) = list.joinToString(", ") { "${Format.floatLiteral(it.offset)} to ${color(it.argb)}" }

    private fun brush(p: FlatPaint): String = when (p) {
        is FlatPaint.Solid -> "SolidColor(${color(p.argb)})"
        is FlatPaint.Linear ->
            "Brush.linearGradient(${stops(p.stops)}, start = Offset(${f(p.x1)}, ${f(p.y1)}), end = Offset(${f(p.x2)}, ${f(p.y2)}))"
        is FlatPaint.Radial ->
            "Brush.radialGradient(${stops(p.stops)}, center = Offset(${f(p.cx)}, ${f(p.cy)}), radius = ${f(p.radius)})"
        is FlatPaint.Sweep ->
            "Brush.sweepGradient(${stops(p.stops)}, center = Offset(${f(p.cx)}, ${f(p.cy)}))"
    }
}
